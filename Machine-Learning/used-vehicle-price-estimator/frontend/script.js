
const brandSelect = document.getElementById("brand");
const modelSelect = document.getElementById("model");
const transmissionSelect = document.getElementById("transmission");
const fuelSelect = document.getElementById("fuel_type");

const form = document.getElementById("prediction-form");
const predictButton = document.getElementById("predict-button");
const buttonText = document.getElementById("button-text");

const resultContent = document.getElementById("result-content");
const errorMessage = document.getElementById("error-message");

let metadata = {};


// Load available car information
async function loadMetadata() {
    try {
        const response = await fetch("/metadata");

        if (!response.ok) {
            throw new Error("Could not load vehicle information.");
        }

        metadata = await response.json();

        // Load brands
        metadata.brands.forEach(brand => {
            const option = document.createElement("option");
            option.value = brand;
            option.textContent = brand;
            brandSelect.appendChild(option);
        });

        // Load transmissions
        metadata.transmissions.forEach(transmission => {
            const option = document.createElement("option");
            option.value = transmission;
            option.textContent = transmission;
            transmissionSelect.appendChild(option);
        });

        // Load fuel types
        metadata.fuel_types.forEach(fuel => {
            const option = document.createElement("option");
            option.value = fuel;
            option.textContent = fuel
                .replaceAll("_", " ")
                .replace(/\b\w/g, letter => letter.toUpperCase());

            fuelSelect.appendChild(option);
        });

        // Set sensible input ranges from the training data
        const yearInput = document.getElementById("year");
        const capacityInput = document.getElementById("capacity");
        const kilometersInput = document.getElementById("kilometers");

        yearInput.min = metadata.year_range[0];
        yearInput.max = metadata.year_range[1];

        capacityInput.min = metadata.energy_capacity_range[0];
        capacityInput.max = metadata.energy_capacity_range[1];

        kilometersInput.min = metadata.kilometers_run_range[0];
        kilometersInput.max = metadata.kilometers_run_range[1];

    } catch (error) {
        errorMessage.textContent = error.message;
    }
}


// Update models when brand changes
brandSelect.addEventListener("change", () => {

    const selectedBrand = brandSelect.value;

    modelSelect.innerHTML = '<option value="">Select model</option>';

    if (!selectedBrand) {
        modelSelect.disabled = true;
        return;
    }

    const availableModels = metadata.brand_models[selectedBrand] || [];

    availableModels.forEach(model => {
        const option = document.createElement("option");
        option.value = model;
        option.textContent = model;
        modelSelect.appendChild(option);
    });

    modelSelect.disabled = false;
});


// Display predicted price
function showPrediction(price) {

    const formattedPrice = new Intl.NumberFormat("en-BD", {
        style: "currency",
        currency: "BDT",
        maximumFractionDigits: 0
    }).format(price);

    resultContent.innerHTML = `
        <div class="placeholder-icon">✓</div>

        <h3>Estimated Vehicle Price</h3>

        <div class="price">${formattedPrice}</div>

        <p class="result-note">
            This is an estimated value generated by our
            Random Forest machine learning model.
            Actual market prices may vary.
        </p>
    `;
}


// Submit prediction request
form.addEventListener("submit", async (event) => {

    event.preventDefault();

    errorMessage.textContent = "";
    predictButton.disabled = true;
    buttonText.textContent = "Calculating...";

    const carData = {
        brand: brandSelect.value,
        model: modelSelect.value,
        transmission: transmissionSelect.value,
        year_of_manufacture: Number(
            document.getElementById("year").value
        ),
        energy_capacity: Number(
            document.getElementById("capacity").value
        ),
        kilometers_run: Number(
            document.getElementById("kilometers").value
        ),
        fuel_type: fuelSelect.value
    };

    try {
        const response = await fetch("/predict", {
            method: "POST",
            headers: {
                "Content-Type": "application/json"
            },
            body: JSON.stringify(carData)
        });

        const result = await response.json();

        if (!response.ok) {
            throw new Error(
                result.detail || "Prediction request failed."
            );
        }

        if (result.error) {
            throw new Error(result.error);
        }

        showPrediction(result.predicted_price);

    } catch (error) {
        errorMessage.textContent = error.message;
    } finally {
        predictButton.disabled = false;
        buttonText.textContent = "Estimate Vehicle Price";
    }
});


// Start the application
loadMetadata();
